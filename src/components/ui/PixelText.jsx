const ALIASES = { '’': "'", '‘': "'", '…': '...', '–': '-', '—': '-', '×': 'X' };
const SPACE = 3;

/** Pixel squares for `text`: { pixels: [[x, y]], width }. Unknown characters are skipped. */
export function textPixels(text) {
  const pixels = [];
  let x = 0;
  const chars = [...String(text || '').toUpperCase()].flatMap((ch) => [...(ALIASES[ch] || ch)]);
  for (const ch of chars) {
    if (ch === ' ') { x += SPACE; continue; }
    const glyph = GLYPHS[ch];
    if (!glyph) continue;
    glyph.forEach((row, y) => [...row].forEach((cell, dx) => { if (cell === '#') pixels.push([x + dx, y]); }));
    x += glyph[0].length + 1;
  }
  return { pixels, width: Math.max(1, x - 1) };
}

/** Width in screen pixels of `text` drawn at `scale`. */
export const pixelTextWidth = (text, scale = 2) => (textPixels(text).width + 1) * scale;

/**
 * Pixel-font label. Inherits `color`; the drop shadow follows `--px-shadow`.
 * The visible text stays available to screen readers through `aria-label` on the
 * button, or pass `title`.
 */
export default function PixelText({ text, scale = 2, className = '' }) {
  const { pixels, width } = useMemo(() => textPixels(text), [text]);
  const path = useMemo(() => pixels.map(([x, y]) => `M${x} ${y}h1v1h-1z`).join(''), [pixels]);
  return (
    <svg
      className={`px-text ${className}`.trim()}
      viewBox={`0 0 ${width + 1} 8`}
      style={{ width: (width + 1) * scale, height: 8 * scale }}
      aria-hidden="true"
      shapeRendering="crispEdges"
      focusable="false"
    >
      <path d={path} className="px-text-shadow" transform="translate(1 1)" />
      <path d={path} className="px-text-face" />
    </svg>
  );
}
